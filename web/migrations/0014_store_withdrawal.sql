-- 店の退会（2026-09-26 本人発案・監査の指摘 安全-20 の残り。要件13の基準 13.13〜13.20）。
--
-- 店が自分で退会すると、店のアカウントとセッション・店舗情報・営業許可書・クーポン・店の画像を消し、公開中のオファーを
-- 終わらせる（usecases/withdrawStore）。過去の確保・通報・運営の操作の記録・取得の記録は消さない——記録の表は追加だけ
-- （基準 27.7）で、運営が「何があったか」を後から確かめる拠り所になるため。
--
-- ⚠️ stores の行は消さない。offers・reservations・fetch_items・selections・reports が外部キーで店の行を指しているので、
--    行を消すと記録ごと消すか外部キーを外すかになる。行は番号だけを残し、店名を「退会した店」に伏せ、ほかの店の情報を空にする。
--    状況（status）は 'banned' にする——承認済みだけを客に出す読み（取得の候補・店の画像・受け取り）と、承認待ちの数から、
--    何も足さずに外れる側へ倒すため。status の CHECK に 'withdrawn' を足すには表を作り直す必要があり（SQLite は CHECK を
--    変えられない）、6本の外部キーに指された表を本番の D1 で作り直す危険を避けた。
--
--   stores.withdrawn_at … 店が退会した時刻。NULL は「退会していない」。運営の画面はこれで「登録取り消し済み」と
--                          「退会済み」を見分け、戻す操作（restoreBannedStore）は退会した店に当たらない。
--
-- ⚠️ 0001・0002 は本番に当たっているので書き換えない（適用済みの migration は編集しない）。
-- ⚠️ 本番へ出す前に、この migration を本番の D1 へ当てる（web/package.json の deploy が先に当てる）。
--    当てずに新しいコードだけを出すと、運営の一覧・詳細が withdrawn_at の列を探して500になる。

ALTER TABLE stores ADD COLUMN withdrawn_at TEXT;
