-- 取得の記録に、探した起点の種類（現在地か、打った場所か）を足す（2026-09-25 監査の指摘 客-11）。
--
-- 確保の応答は、経路の出発地として「その確保を選んだ取得の起点」の座標を返している（打った場所で探した客の
-- 経路が現在地から引かれた件の直し）。ところが記録に起点の種類が無く、現在地で探した客にも、探した時点の
-- 座標が固定の出発地として付いていた。種類を残し、現在地で探した確保には出発地を付けない
-- （lib/repo/reservations.ts・マップが今の現在地から引く）。
--
--   here  … 端末の現在地（座標）で探した
--   place … 客が打った場所の文字を、サーバーが座標に直して探した
--
-- 既に在る行は NULL のまま残る（どちらで探したか分からない）。コードは NULL を今までどおり座標つきで返す
-- ——記録の表は追加だけで、書き換えない（基準 27.7）。
--
-- ⚠️ 0001・0002 は本番に当たっているので書き換えない（適用済みの migration は編集しない）。
-- ⚠️ 本番へ出す前に、この migration を本番の D1 へ当てる（web/package.json の deploy が先に当てる）。
--    当てずに新しいコードだけを出すと、取得の記録を書く文と確保を読む文が列の無さで落ちる。

ALTER TABLE fetch_logs ADD COLUMN origin_kind TEXT CHECK (origin_kind IS NULL OR origin_kind IN ('here', 'place'));
