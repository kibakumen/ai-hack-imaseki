-- セッションに作った時刻を足す（2026-09-25 監査の指摘 安全-08）。
--
-- それまでのセッションは、使われるたびに「今から25時間」へ延びるだけで、絶対の寿命が無かった
-- （表に作った時刻の列が無く、どれだけ古いセッションかを見分けられなかった）。盗まれたセッションや
-- 置き忘れたセッションが、使い続けられる限り切れなかった。作った時刻から数えて14日
-- （lib/schemas/limits.ts の SESSION_ABSOLUTE_MAX_SECONDS）で必ず切る。
--
-- 既に在る行は created_at が NULL のまま残る。コードは作った時刻の読めない行を**切れたものとして断る**
-- （フェイルクローズ・lib/http/guards.ts）ので、この migration を当てて新しいコードを出すと、店と運営は
-- 1度ずつ入り直すことになる。公開デモの乗っ取り（安全-01）で残っているかもしれない他人のセッションも、
-- ここで一緒に切れる。
--
-- ⚠️ 0001・0002 は本番に当たっているので書き換えない（適用済みの migration は編集しない）。
-- ⚠️ 本番へ出す前に、この migration を本番の D1 へ当てる（web/package.json の deploy が先に当てる）。
--    当てずに新しいコードだけを出すと、セッションを書く文と読む文が列の無さで落ち、ログインが全部500になる。

ALTER TABLE sessions ADD COLUMN created_at TEXT;
